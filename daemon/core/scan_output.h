/* ============================================================================
 *  scan_output.h  --  스캔 산출물 생성 (organized 격자 -> .json / .pcd)
 * ----------------------------------------------------------------------------
 *  담당: 이현우
 *
 *  ★ 이 계층은 "격자에 점을 담고 파일로 뱉는 것"만 한다.
 *    epoll / fd / ioctl / 상태머신은 core(main.c) 소관이고, 여기엔 없다.
 *
 *  왜 나눴나:
 *    ① **좌표계와 파일 포맷 계약이 전부 여기 모인다.** JSON 인터페이스,
 *      PCD 헤더, schema_version, 기구각->계약각 변환, 라이다 오프셋. 이 변경을
 *      몰고 오는 건 디바이스 작업이 아니라 소비자(카메라 단 캘리브)다.
 *      한 파일에 모아두면 "변환식은 여기 하나뿐"이 구조로 보장된다 — 같은
 *      식이 두 군데 있으면 오프셋 같은 걸 한 쪽만 고치는 사고가 난다.
 *    ② **리눅스 전용 API를 쓰지 않는 유일한 부분이다.** epoll/timerfd/ioctl 이
 *      없어 호스트(맥/우분투)에서 그대로 링크해 격자·좌표변환을 검증할 수 있다.
 *      그동안은 실기 전 검증을 위해 main.c 에서 함수를 손으로 추출해야 했다.
 *
 *  ⚠️ core 의 struct 를 노출하지 않는다(불투명 핸들). core 가 이 파일의
 *    내부 필드를 직접 만지기 시작하면 나눈 의미가 없어진다.
 * ==========================================================================*/
#ifndef SCAN_OUTPUT_H
#define SCAN_OUTPUT_H

#include "daemon_module.h"   /* struct scan_request, core_log */
#include "protocol.h"        /* struct proto_scan_point */

/* ⚠️ 이 헤더가 protocol.h 를 끌고 들어온다. protocol.h 의 ioctl 구역은
 *   PROTO_WANT_IOCTL(또는 __KERNEL__)로 가려져 있고, 인클루드 가드 때문에
 *   **한 번 처리되면 다시 안 읽는다.** 그래서 ioctl 이 필요한 TU 는 반드시
 *
 *       #define PROTO_WANT_IOCTL 1     <- 먼저
 *       #include "scan_output.h"       <- 그 다음
 *
 *   순서를 지켜야 한다. 뒤집으면 ioctl 없는 protocol.h 가 캐시돼 나중에
 *   #define 을 해도 소용없고, 진단은 "TURRET_HOME 이 없다" 로만 나와
 *   원인을 찾기 어렵다. (main.c 는 21행에서 먼저 정의한다) */

#include <stdbool.h>
#include <stdint.h>

/* ---------------------------------------------------------------------------
 *  라이다 원점 오프셋 (기구 상수, 2026-08-07 실측 84mm)
 *
 *  라이다가 보고하는 거리는 **자기 발광면부터** 표적까지다. 그런데 좌표계
 *  원점은 팬/틸트 **회전축 교점**이다(회전해도 안 움직이는 유일한 점이라
 *  원점이 될 수 있는 것도 거기뿐이다). 라이다는 틸트 브래킷에 실려 축과
 *  같이 돌므로, 발광면은 원점에서 빔 방향으로 항상 이만큼 앞서 있다.
 *
 *      원점(축교점) ●────84mm────▷ 발광면 ────── d(라이다 보고) ──────▶ 표적
 *                   └──────────── r = d + 84mm ───────────────────────┘
 *
 *  발광면이 빔 축 위에 있으므로(횡방향 어긋남 없음) 보정은 **방향은 그대로
 *  두고 거리에만 더하는 순수 스칼라**다. 각도 변환식은 손댈 필요가 없다.
 *
 *  ⚠️ 이걸 빼먹으면 스캔한 장면 전체가 원점을 향해 84mm 수축한다. 그런데
 *    수축은 **평행이동이 아니라 각 점의 시선 방향**이라, 평평한 면이 평평하게
 *    나오지 않는다. 법선에서 α 만큼 벌어진 빔이 거리 H 의 평면을 볼 때
 *
 *        참값 r = H/cos α          →  보정 없이 찍으면 수직거리 H − 84·cos α
 *
 *    즉 정면(α=0)에서 84mm, α=30도에서 73mm 만큼 당겨져 **가운데가 파인
 *    사발 모양**으로 휜다. 평면 피팅 잔차에 곡률로 남는다.
 *
 *    → 검증 가능한 예측: 2026-07-30 스캔은 "수직거리 1.5578m, 잔차 RMS
 *      11.0mm" 였는데, 피팅에 쓰인 α 범위가 ±30도 근처였다면 그 11mm 는
 *      상당 부분 센서 잡음이 아니라 **이 누락**이다(84·(1−cos30)=11.3mm).
 *      보정 후 같은 자리를 다시 찍어 RMS 가 유의하게 떨어지면 확정.
 *      거리도 1.5578 → 약 1.6418m 로 올라가야 한다.
 *
 *  ⚠️ 횡방향(빔에 수직인) 어긋남은 0 으로 가정한다. 조립상 발광면이 축 옆으로
 *    비켜 있다면 이 스칼라 보정으로는 부족하고 회전 프레임에서 벡터로 더해야
 *    한다. 지금 기구는 빔 축 위에 있어 해당 없음.
 * ------------------------------------------------------------------------- */
#define LIDAR_RANGE_OFFSET_MM   84

/* 불투명 핸들. 내부 구조는 scan_output.c 에만 있다. */
struct scan_out;

/* ---------------------------------------------------------------------------
 *  수명주기
 * ------------------------------------------------------------------------- */

/* 격자를 할당하고 출력 경로를 정한다. 실패 시 NULL (이유는 로그로 남는다).
 *
 *   req              스캔 요청(기구각). 격자 기하 계산에 계속 쓰이므로 사본을 둔다.
 *   lidar_offset_mm  축교점→발광면 거리. 좌표에 **적용된다**.
 *   log_core         core_log() 에 그대로 넘길 불투명 포인터. NULL 이면 무로그.
 *
 * ⚠️ 파일은 여기서 만들지 않는다. 격자를 다 채운 뒤 close 시점에 한 번에 쓴다
 *   — organized 산출물은 미측정 셀을 null/NaN 으로 명시해야 하고, 그건 스캔이
 *   끝나야 확정되기 때문이다. */
struct scan_out *scan_out_open(const struct scan_request *req,
                               int32_t lidar_offset_mm,
                               void *log_core);

/* 점 하나를 격자에 배치. 기구각->계약각 변환과 셀 병합이 여기서 일어난다. */
void scan_out_add(struct scan_out *o, const struct proto_scan_point *p);

/* 홈 provenance 기록 (산출물 헤더의 mechanism.home).
 * 안 부르면 null 로 나가 "홈을 안 거쳤다" 와 "0 이었다" 가 구분된다.
 *
 * ⚠️ turret_link_state 를 그대로 받지 않고 값으로 푼다. 그 구조체는 ioctl
 *   인터페이스(PROTO_WANT_IOCTL)에 묶여 있어서, 받는 순간 이 파일이 커널
 *   경계에 의존하게 되고 호스트 테스트가 깨진다. */
void scan_out_set_home(struct scan_out *o,
                       uint16_t pan_raw, uint16_t tilt_raw,
                       int16_t pan_ddeg, int16_t tilt_ddeg);

/* 산출물(.json + .pcd) 을 쓰고 해제한다. *o 는 NULL 이 된다.
 * *o 가 이미 NULL 이면 아무것도 하지 않는다 — 중단/종료 경로에서 중복 호출된다. */
void scan_out_close(struct scan_out **o);

/* ---------------------------------------------------------------------------
 *  관측 (core 가 진행률·결과 보고에 쓴다)
 * ------------------------------------------------------------------------- */
uint32_t    scan_out_point_count(const struct scan_out *o);  /* 격자에 담긴 유효 점 */
const char *scan_out_path(const struct scan_out *o);         /* .pcd 경로 */
/* 원시 측정 JSON 경로. 카메라 단이 받는 것은 이쪽이다.
 * ⚠️ .pcd 경로에서 확장자를 갈아끼워 만들지 말 것 — 파일명 규칙이 두 곳에
 *   살게 되어 한쪽만 바뀔 때 조용히 깨진다. */
const char *scan_out_json_path(const struct scan_out *o);

/* ---------------------------------------------------------------------------
 *  격자 기하 (핸들 없이도 요청만으로 답할 수 있는 것들)
 * ------------------------------------------------------------------------- */

/* 요청 범위·격자로 예상 점 수 산출 (진행률 분모). */
uint32_t scan_out_expected_points(const struct scan_request *r);

/* 팬 양끝이 같은 평면을 훑는 요청이면 경고를 남긴다.
 * 2축 스윕은 한 줄이 방위 p 와 p+180 을 함께 훑으므로 팬을 0~180 **양끝 포함**
 * 으로 돌리면 첫 줄과 마지막 줄이 겹친다. (한 바퀴 − 1스텝)까지가 정답. */
void scan_out_warn_seam(const struct scan_request *r, void *log_core);

#endif /* SCAN_OUTPUT_H */
